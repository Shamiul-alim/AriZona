async function summarise(): Promise<Record<string, number>> {
  const [anime, episodes, sources, variants, subtitles, users, posts, comments, requests] = await Promise.all([
    prisma.anime.count(),
    prisma.episode.count(),
    prisma.mediaSource.count(),
    prisma.mediaVariant.count(),
    prisma.subtitleTrack.count(),
    prisma.user.count(),
    prisma.communityPost.count(),
    prisma.comment.count(),
    prisma.animeRequest.count(),
  ]);
  return {
    anime,
    episodes,
    'media sources': sources,
    'quality variants': variants,
    'subtitle tracks': subtitles,
    users,
    'community posts': posts,
    comments,
    'anime requests': requests,
  };
}

