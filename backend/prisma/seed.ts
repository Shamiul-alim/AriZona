function seasonMonth(season: SeedAnime['season']): number {
  return { WINTER: 0, SPRING: 3, SUMMER: 6, FALL: 9 }[season];
}

async function seedEpisodes(animeId: string, entry: SeedAnime, animeSlug: string): Promise<void> {
  if (entry.status === 'UPCOMING') return;

  const existing = await prisma.episode.count({ where: { animeId } });
  if (existing > 0) return;

  for (let n = 1; n <= entry.episodeCount; n += 1) {
    const title = entry.episodeTitles[n - 1] ?? `Episode ${n}`;
    const thumbnailUrl = await writeArt(
      UPLOADS_ROOT,
      PUBLIC_BASE,
      'thumbnails',
      `${animeSlug}-ep${n}.svg`,
      thumbnailSvg(entry.titleEnglish, n),
    );

    const episode = await prisma.episode.create({
      data: {
        animeId,
        number: n,
        title,
        description: `Demo episode ${n} of ${entry.titleEnglish}.`,
        thumbnailUrl,
        durationSeconds: entry.type === 'MOVIE' ? DEMO.durationSeconds : DEMO.durationSeconds,
        airDate: new Date(entry.releaseYear, seasonMonth(entry.season), 6 + (n - 1) * 7),
        hasSub: true,
        hasDub: entry.hasDub,
        introStart: DEMO.intro.start,
        introEnd: DEMO.intro.end,
        outroStart: DEMO.outro.start,
        outroEnd: DEMO.outro.end,
        publishStatus: PublishStatus.PUBLISHED,
      },
    });

    // Subtitled source: four real renditions, so quality switching is genuine.
    const subSource = await prisma.mediaSource.create({
      data: {
        episodeId: episode.id,
        label: 'Server 1',
        provider: MediaProvider.DIRECT_FILE,
        kind: MediaKind.SUB,
        audioLanguage: 'ja',
        audioLabel: 'Japanese',
        priority: 0,
        isDefault: true,
      },
    });
    await prisma.mediaVariant.createMany({
      data: DEMO.sub.map((v, i) => ({
        mediaSourceId: subSource.id,
        quality: v.quality,
        directUrl: v.path,
        mimeType: 'video/mp4',
        width: v.width,
        height: v.height,
        isDefault: i === 1,
      })),
    });

    // Dubbed source: a separate file, because a progressive MP4 carries one
    // audio track. Switching audio therefore switches source — honestly.
    if (entry.hasDub) {
      const dubSource = await prisma.mediaSource.create({
        data: {
          episodeId: episode.id,
          label: 'Server 1',
          provider: MediaProvider.DIRECT_FILE,
          kind: MediaKind.DUB,
          audioLanguage: 'en',
          audioLabel: 'English Dub',
          priority: 1,
        },
      });
      await prisma.mediaVariant.createMany({
        data: DEMO.dub.map((v, i) => ({
          mediaSourceId: dubSource.id,
          quality: v.quality,
          directUrl: v.path,
          mimeType: 'video/mp4',
          width: v.width,
          height: v.height,
          isDefault: i === 0,
        })),
      });
    }

    await prisma.subtitleTrack.createMany({
      data: DEMO.subtitles.map((s) => ({
        episodeId: episode.id,
        mediaSourceId: null,
        language: s.language,
        label: s.label,
        format: SubtitleFormat.VTT,
        url: s.path,
        isDefault: s.isDefault,
      })),
    });
  }
}

async function seedRelations(animeIds: Map<string, string>): Promise<void> {
  const pairs: Array<[string, string, RelationKind]> = [
    ['Crimson Vanguard', 'Thunderstep Academy', RelationKind.ALTERNATIVE],
    ['Starlight Requiem', 'Summer of Falling Stars', RelationKind.SIDE_STORY],
    ['Glass Horizon', 'Orbital Gardeners', RelationKind.SPIN_OFF],
    ['Echo Protocol Zero', 'Glass Horizon', RelationKind.ALTERNATIVE],
    ['Aether Blade Chronicles', 'Fangs of the Silver Moon', RelationKind.SEQUEL],
  ];

  for (const [from, to, kind] of pairs) {
    const a = animeIds.get(from);
    const b = animeIds.get(to);
    if (!a || !b) continue;
    await prisma.animeRelation.upsert({
      where: { animeId_relatedAnimeId: { animeId: a, relatedAnimeId: b } },
      create: { animeId: a, relatedAnimeId: b, kind },
      update: { kind },
    });
    await prisma.animeRecommendation.upsert({
      where: { animeId_recommendedAnimeId: { animeId: a, recommendedAnimeId: b } },
      create: { animeId: a, recommendedAnimeId: b, weight: 10 },
      update: {},
    });
  }
}

async function seedFeatured(animeIds: Map<string, string>): Promise<void> {
  const featured = ANIME.filter((a) => a.featured);
  for (const [index, entry] of featured.entries()) {
    const animeId = animeIds.get(entry.titleEnglish);
    if (!animeId) continue;
    await prisma.featuredAnime.upsert({
      where: { animeId },
      create: { animeId, headline: entry.titleEnglish, subtitle: entry.tagline, order: index, ctaLabel: 'Watch Now' },
      update: { headline: entry.titleEnglish, subtitle: entry.tagline, order: index },
    });
  }
}

/** Gives Trending Day/Week/Month something real to rank on a fresh install. */
async function seedViewStats(animeIds: Map<string, string>): Promise<void> {
  const ids = [...animeIds.values()];
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);

  for (const [index, animeId] of ids.entries()) {
    let total = 0;
    for (let d = 0; d < 30; d += 1) {
      const day = new Date(today);
      day.setUTCDate(day.getUTCDate() - d);
      // Deterministic but varied: popular titles trend higher and decay slower.
      const base = 400 - index * 22;
      const views = Math.max(5, Math.round(base * Math.exp(-d / 14) * (0.7 + ((index * 7 + d * 13) % 11) / 18)));
      total += views;
      await prisma.animeViewStat.upsert({
        where: { animeId_day: { animeId, day } },
        create: { animeId, day, views },
        update: { views },
      });
    }
    await prisma.anime.update({
      where: { id: animeId },
      data: { viewCount: total, popularity: total },
    });
  }
}

async function seedEngagement(
  animeIds: Map<string, string>,
  users: Array<{ id: string }>,
): Promise<void> {
  const ids = [...animeIds.values()];
  const statuses = [
    WatchStatus.WATCHING,
    WatchStatus.COMPLETED,
    WatchStatus.PLAN_TO_WATCH,
    WatchStatus.ON_HOLD,
    WatchStatus.DROPPED,
  ];

  const commentBodies = [
    'The pacing in this one is doing something I have not seen in a while. Genuinely patient.',
    'Episode 4 completely recontextualises the first three. Worth sticking with.',
    'The background art alone is carrying half the mood here.',
    'I was ready to drop this at episode 2 and I am very glad I did not.',
    'Sound design deserves more credit than it is getting.',
    'This is the rare show where the quiet episodes are the strong ones.',
    'Rewatching with subtitles on and catching a lot I missed.',
    'Not sure the ending lands for me, but the journey absolutely did.',
  ];

  for (const [i, user] of users.entries()) {
    for (let k = 0; k < 6; k += 1) {
      const animeId = pick(ids, i * 5 + k);

      await prisma.watchlistEntry.upsert({
        where: { userId_animeId: { userId: user.id, animeId } },
        create: {
          userId: user.id,
          animeId,
          status: pick(statuses, i + k),
          progressEpisodes: (i + k) % 9,
        },
        update: {},
      });

      if (k % 2 === 0) {
        const score = 6 + ((i * 3 + k * 5) % 5);
        await prisma.rating.upsert({
          where: { userId_animeId: { userId: user.id, animeId } },
          create: { userId: user.id, animeId, score },
          update: { score },
        });
      }

      if (k % 3 === 0) {
        await prisma.favorite.upsert({
          where: { userId_animeId: { userId: user.id, animeId } },
          create: { userId: user.id, animeId },
          update: {},
        });
      }
    }
  }

  // Recompute the denormalised score columns from the ratings just written.
  for (const animeId of ids) {
    const aggregate = await prisma.rating.aggregate({
      where: { animeId },
      _avg: { score: true },
      _count: { _all: true },
    });
    const favouriteCount = await prisma.favorite.count({ where: { animeId } });
    await prisma.anime.update({
      where: { id: animeId },
      data: {
        score: Number((aggregate._avg.score ?? 0).toFixed(2)),
        scoreCount: aggregate._count._all,
        favoriteCount: favouriteCount,
      },
    });
  }

  // A few episode comments with a reply thread and some votes.
  const episodes = await prisma.episode.findMany({
    where: { number: { lte: 3 } },
    take: 12,
    select: { id: true },
    orderBy: { createdAt: 'asc' },
  });

  for (const [i, episode] of episodes.entries()) {
    const author = pick(users, i);
    const root = await prisma.comment.create({
      data: {
        userId: author.id,
        episodeId: episode.id,
        body: pick(commentBodies, i),
        upvoteCount: (i * 3) % 14,
      },
    });

    if (i % 2 === 0) {
      const replier = pick(users, i + 2);
      await prisma.comment.create({
        data: {
          userId: replier.id,
          episodeId: episode.id,
          parentId: root.id,
          body: 'Completely agree — the second half of that episode is the strongest stretch so far.',
          upvoteCount: i % 5,
        },
      });
      await prisma.comment.update({ where: { id: root.id }, data: { replyCount: 1 } });
    }
  }

  // Partial watch progress, so "Continue watching" has real entries.
  const firstEpisodes = await prisma.episode.findMany({
    where: { number: { in: [1, 2] } },
    take: 10,
    include: { anime: { select: { id: true } } },
    orderBy: { createdAt: 'asc' },
  });

  for (const [i, episode] of firstEpisodes.entries()) {
    const user = pick(users, i);
    const position = 18 + ((i * 11) % 50);
    await prisma.watchProgress.upsert({
      where: { userId_episodeId: { userId: user.id, episodeId: episode.id } },
      create: {
        userId: user.id,
        episodeId: episode.id,
        animeId: episode.anime.id,
        positionSeconds: position,
        durationSeconds: DEMO.durationSeconds,
        percent: Math.round((position / DEMO.durationSeconds) * 100),
      },
      update: {},
    });
    await prisma.watchHistory.create({
      data: { userId: user.id, episodeId: episode.id, animeId: episode.anime.id },
    });
  }
}

async function seedCommunity(
  animeIds: Map<string, string>,
  users: Array<{ id: string }>,
): Promise<void> {
  const categories = new Map<string, string>();
  for (const [index, c] of COMMUNITY_CATEGORIES.entries()) {
    const row = await prisma.communityCategory.upsert({
      where: { name: c.name },
      create: {
        name: c.name,
        slug: slugify(c.name),
        description: c.description,
        color: c.color,
        icon: c.icon,
        order: index,
        staffOnly: c.staffOnly ?? false,
      },
      update: { description: c.description, color: c.color, icon: c.icon, order: index },
    });
    categories.set(c.name, row.id);
  }

  if ((await prisma.communityPost.count()) > 0) return;

  const ids = [...animeIds.values()];

  const textPosts: Array<{ category: string; title: string; body: string; pinned?: boolean }> = [
    {
      category: 'Updates',
      title: 'Welcome to the AniZora community board',
      body: '<p>This is the place for discussion, recommendations, tier lists and polls. A few ground rules: tag spoilers, keep it civil, and use the report button rather than arguing with someone who is clearly baiting.</p><p>Posting and commenting earn Mana, which advances your rank. Ranks are cosmetic — they signal that someone has been around, nothing more.</p>',
      pinned: true,
    },
    {
      category: 'Discussion',
      title: 'Shows where the quiet episodes are the strongest',
      body: '<p>I keep noticing that the episodes I remember are almost never the big ones. Midnight Ramen Diaries is the obvious example but Starlight Requiem does it too — the rehearsal episodes land harder than the performance.</p><p>What else fits?</p>',
    },
    {
      category: 'Question',
      title: 'How do I get subtitles to stay on between episodes?',
      body: '<p>Every time autoplay moves to the next episode my subtitle selection resets. Am I missing a setting somewhere?</p>',
    },
    {
      category: 'Suggestion',
      title: 'Per-series default audio preference',
      body: '<p>I watch some things subbed and some dubbed, and a single global preference does not really capture that. Would it be possible to remember the choice per series instead?</p>',
    },
    {
      category: 'Seasonal',
      title: 'Fall 2026 — what is everyone actually keeping?',
      body: '<p>Three episodes in for most things now. I have dropped more than I have kept this season, which is unusual. Crimson Vanguard and Ironheart Meridian are the only two I am still genuinely looking forward to.</p>',
    },
    {
      category: 'Feedback',
      title: 'The A-Z browser is much faster than it used to be',
      body: '<p>Whatever changed on the listing pages, it is noticeably quicker on mobile. Wanted to say so rather than only posting when something breaks.</p>',
    },
  ];

  for (const [i, post] of textPosts.entries()) {
    const categoryId = categories.get(post.category);
    if (!categoryId) continue;
    await prisma.communityPost.create({
      data: {
        userId: pick(users, i).id,
        categoryId,
        title: post.title,
        slug: slugify(post.title),
        body: post.body,
        kind: CommunityPostKind.TEXT,
        isPinned: post.pinned ?? false,
        upvoteCount: 4 + i * 3,
        viewCount: 60 + i * 37,
      },
    });
  }

  // --- A poll -------------------------------------------------------------
  const pollPost = await prisma.communityPost.create({
    data: {
      userId: pick(users, 1).id,
      categoryId: categories.get('Poll')!,
      title: 'Which format do you actually prefer for a long-running series?',
      slug: slugify('Which format do you actually prefer for a long running series'),
      body: '<p>Curious how this splits. Assume the production quality is identical either way.</p>',
      kind: CommunityPostKind.POLL,
      upvoteCount: 22,
      viewCount: 410,
    },
  });
  const poll = await prisma.poll.create({
    data: { postId: pollPost.id, question: 'Preferred release format?', totalVotes: 0 },
  });
  await prisma.pollOption.createMany({
    data: [
      { pollId: poll.id, text: 'Weekly episodes', order: 0, voteCount: 41 },
      { pollId: poll.id, text: 'Full season at once', order: 1, voteCount: 27 },
      { pollId: poll.id, text: 'Two-episode weekly blocks', order: 2, voteCount: 14 },
      { pollId: poll.id, text: 'Cour splits with a break', order: 3, voteCount: 9 },
    ],
  });
  await prisma.poll.update({ where: { id: poll.id }, data: { totalVotes: 91 } });

  // --- A matchup (a poll with exactly two options) -------------------------
  const matchupPost = await prisma.communityPost.create({
    data: {
      userId: pick(users, 3).id,
      categoryId: categories.get('Matchup')!,
      title: 'Glass Horizon vs Echo Protocol Zero — which handles institutional failure better?',
      slug: slugify('Glass Horizon vs Echo Protocol Zero'),
      body: '<p>Both are about a system quietly failing while everyone involved has a reason not to escalate. Which one sticks the landing?</p>',
      kind: CommunityPostKind.MATCHUP,
      upvoteCount: 31,
      viewCount: 620,
    },
  });
  const matchupPoll = await prisma.poll.create({
    data: { postId: matchupPost.id, question: 'Pick one', totalVotes: 58 },
  });
  await prisma.pollOption.createMany({
    data: [
      { pollId: matchupPoll.id, text: 'Glass Horizon', order: 0, voteCount: 33, animeId: animeIds.get('Glass Horizon') },
      { pollId: matchupPoll.id, text: 'Echo Protocol Zero', order: 1, voteCount: 25, animeId: animeIds.get('Echo Protocol Zero') },
    ],
  });

  // --- A tier list --------------------------------------------------------
  const tierPost = await prisma.communityPost.create({
    data: {
      userId: pick(users, 2).id,
      categoryId: categories.get('Tier List')!,
      title: 'My completely indefensible 2025 tier list',
      slug: slugify('My completely indefensible 2025 tier list'),
      body: '<p>Ranked purely on how often I have thought about them since finishing. Argue in the comments.</p>',
      kind: CommunityPostKind.TIER_LIST,
      upvoteCount: 18,
      viewCount: 295,
    },
  });
  const tierAssignments: Array<[string, TierLevel]> = [
    ['Starlight Requiem', TierLevel.S],
    ['Glass Horizon', TierLevel.S],
    ['Midnight Ramen Diaries', TierLevel.A],
    ['Echo Protocol Zero', TierLevel.A],
    ['The Last Alchemy Club', TierLevel.B],
    ['Summer of Falling Stars', TierLevel.B],
    ['Paper Lanterns of Yomi', TierLevel.C],
  ];
  await prisma.tierListItem.createMany({
    data: tierAssignments
      .filter(([title]) => animeIds.has(title))
      .map(([title, tier], order) => ({
        postId: tierPost.id,
        tier,
        label: title,
        animeId: animeIds.get(title)!,
        order,
      })),
  });

  // --- A recommendation post ----------------------------------------------
  const recPost = await prisma.communityPost.create({
    data: {
      userId: pick(users, 4).id,
      categoryId: categories.get('Recommend')!,
      title: 'Three shows to watch if you like competence over spectacle',
      slug: slugify('Three shows to watch if you like competence over spectacle'),
      body: '<p>All three are about people who are very good at unglamorous jobs. No chosen ones, no tournaments.</p>',
      kind: CommunityPostKind.RECOMMENDATION,
      upvoteCount: 26,
      viewCount: 380,
    },
  });
  const recTitles = ['Orbital Gardeners', 'Glass Horizon', 'Ironheart Meridian'];
  await prisma.communityPostAnime.createMany({
    data: recTitles
      .filter((t) => animeIds.has(t))
      .map((t, order) => ({
        postId: recPost.id,
        animeId: animeIds.get(t)!,
        order,
        note: 'Quietly excellent at what it sets out to do.',
      })),
  });

  // Comments across the board.
  const posts = await prisma.communityPost.findMany({ select: { id: true } });
  const replies = [
    'Strong agree on the second one. The third is a harder sell but it got me eventually.',
    'This is a good list and I am annoyed that I cannot argue with any of it.',
    'Bookmarking. Half of these have been on my list for months.',
    'Interesting framing — I had not thought about it that way.',
  ];
  for (const [i, post] of posts.entries()) {
    const count = (i % 3) + 1;
    for (let k = 0; k < count; k += 1) {
      await prisma.communityComment.create({
        data: {
          postId: post.id,
          userId: pick(users, i + k + 1).id,
          body: pick(replies, i + k),
          upvoteCount: (i + k) % 7,
        },
      });
    }
    await prisma.communityPost.update({ where: { id: post.id }, data: { commentCount: count } });
  }
}

